#!/usr/bin/env bash
set -euo pipefail
PRETRAIN_DIR="$(cd "$(dirname "$0")/.." && pwd)"
source "$PRETRAIN_DIR/scripts/e2e_common.sh"

export FINETUNE_MODE="${FINETUNE_MODE:-adapter}"
PORT_SEED="${SLURM_JOB_ID:-$$}"
export MASTER_PORT="${MASTER_PORT:-$((20000 + PORT_SEED % 20000))}"
export ADAPTER_TYPE="${ADAPTER_TYPE:-engram}"
export ADAPTER_LAYERS="${ADAPTER_LAYERS:-1,14}"
export ADAPTER_HIDDEN_SIZE="${ADAPTER_HIDDEN_SIZE:-256}"
export ADAPTER_MEMORY_SIZE="${ADAPTER_MEMORY_SIZE:-65521}"
export ADAPTER_MEMORY_INIT="${ADAPTER_MEMORY_INIT:-default}"
export ADAPTER_MEMORY_INIT_STD="${ADAPTER_MEMORY_INIT_STD:-0.01}"
export ADAPTER_MEMORY_PROTOTYPE_PATH="${ADAPTER_MEMORY_PROTOTYPE_PATH:-$PRETRAIN_DIR/../model_output/prototypes_recif_videorec_pretrain_10pct/engram/engram_proto_tokenemb_randomproj2048to128_seed42_ng2-3_heads8_mem65521.pt}"
export ADAPTER_NGRAM_ORDER="${ADAPTER_NGRAM_ORDER:-3}"
export ADAPTER_TOPK="${ADAPTER_TOPK:-8}"
export ADAPTER_LNGRAM_BITS_PER_ROUTE="${ADAPTER_LNGRAM_BITS_PER_ROUTE:-4}"
export ADAPTER_USE_ALPHA_LAYER="${ADAPTER_USE_ALPHA_LAYER:-false}"
export ADAPTER_ALPHA_INIT="${ADAPTER_ALPHA_INIT:-0.1}"
export ADAPTER_FIXED_CONTEXT_GATE="${ADAPTER_FIXED_CONTEXT_GATE:-}"
export ADAPTER_DISABLE_CONV="${ADAPTER_DISABLE_CONV:-false}"
export ADAPTER_USE_SID_SPAN="${ADAPTER_USE_SID_SPAN:-false}"
if [ "$ADAPTER_DISABLE_CONV" = "true" ]; then ADAPTER_CONV_TAG=off; else ADAPTER_CONV_TAG=on; fi
if [ "$ADAPTER_MEMORY_INIT" = "default" ]; then ADAPTER_INIT_TAG=""; else ADAPTER_INIT_TAG="_init${ADAPTER_MEMORY_INIT}"; fi
if [[ "$ADAPTER_TYPE" == "lngram" ]]; then
  E2E_DEFAULT_TAG="${ADAPTER_TYPE}_layers${ADAPTER_LAYERS//,/-}_ng${ADAPTER_NGRAM_ORDER}_bits${ADAPTER_LNGRAM_BITS_PER_ROUTE:-4}_d${ADAPTER_HIDDEN_SIZE}${ADAPTER_INIT_TAG}_alpha${ADAPTER_USE_ALPHA_LAYER}-${ADAPTER_ALPHA_INIT}_gate${ADAPTER_FIXED_CONTEXT_GATE:-dynamic}_conv${ADAPTER_CONV_TAG}"
else
  E2E_DEFAULT_TAG="${ADAPTER_TYPE}_layers${ADAPTER_LAYERS//,/-}_ng${ADAPTER_NGRAM_ORDER}_heads${ADAPTER_TOPK}_mem${ADAPTER_MEMORY_SIZE}_d${ADAPTER_HIDDEN_SIZE}${ADAPTER_INIT_TAG}_alpha${ADAPTER_USE_ALPHA_LAYER}-${ADAPTER_ALPHA_INIT}_gate${ADAPTER_FIXED_CONTEXT_GATE:-dynamic}_conv${ADAPTER_CONV_TAG}_sid${ADAPTER_USE_SID_SPAN}"
fi
export E2E_RUN_TAG="${E2E_RUN_TAG:-${ADAPTER_RUN_TAG:-$E2E_DEFAULT_TAG}}"
export E2E_MERGE_LORA=false
export E2E_STAGE2_BUNDLE_REMOTE_CODE=0
export E2E_SFT_BUNDLE_REMOTE_CODE=1
run_e2e_pipeline
