#!/usr/bin/env bash
set -euo pipefail
PRETRAIN_DIR="$(cd "$(dirname "$0")/.." && pwd)"
source "$PRETRAIN_DIR/scripts/e2e_common.sh"

export FINETUNE_MODE="${FINETUNE_MODE:-adapter_lora}"
PORT_SEED="${SLURM_JOB_ID:-$$}"
export MASTER_PORT="${MASTER_PORT:-$((20000 + PORT_SEED % 20000))}"
export ADAPTER_TYPE="${ADAPTER_TYPE:-engram}"
export ADAPTER_LAYERS="${ADAPTER_LAYERS:-1,14}"
export ADAPTER_HIDDEN_SIZE="${ADAPTER_HIDDEN_SIZE:-256}"
export ADAPTER_MEMORY_SIZE="${ADAPTER_MEMORY_SIZE:-65521}"
export ADAPTER_NGRAM_ORDER="${ADAPTER_NGRAM_ORDER:-3}"
export ADAPTER_TOPK="${ADAPTER_TOPK:-8}"
export ADAPTER_LNGRAM_BITS_PER_ROUTE="${ADAPTER_LNGRAM_BITS_PER_ROUTE:-4}"
export ADAPTER_USE_ALPHA_LAYER="${ADAPTER_USE_ALPHA_LAYER:-false}"
export ADAPTER_ALPHA_INIT="${ADAPTER_ALPHA_INIT:-0.1}"
export ADAPTER_FIXED_CONTEXT_GATE="${ADAPTER_FIXED_CONTEXT_GATE:-}"
export ADAPTER_DISABLE_CONV="${ADAPTER_DISABLE_CONV:-false}"
export ADAPTER_USE_SID_SPAN="${ADAPTER_USE_SID_SPAN:-false}"
export LORA_RANK="${LORA_RANK:-384}"
export LORA_ALPHA="${LORA_ALPHA:-768}"
export LORA_DROPOUT="${LORA_DROPOUT:-0.05}"
export LORA_TARGET_MODULES="${LORA_TARGET_MODULES:-q_proj,k_proj,v_proj,o_proj}"
export LORA_LAYERS="${LORA_LAYERS:-}"
if [ "$ADAPTER_DISABLE_CONV" = "true" ]; then ADAPTER_CONV_TAG=off; else ADAPTER_CONV_TAG=on; fi
if [[ "$ADAPTER_TYPE" == "lngram" ]]; then
  E2E_DEFAULT_TAG="${ADAPTER_TYPE}_lora_${LORA_TARGET_MODULES//,/-}_r${LORA_RANK}_a${LORA_ALPHA}_ng${ADAPTER_NGRAM_ORDER}_bits${ADAPTER_LNGRAM_BITS_PER_ROUTE:-4}_d${ADAPTER_HIDDEN_SIZE}_alpha${ADAPTER_USE_ALPHA_LAYER}-${ADAPTER_ALPHA_INIT}_gate${ADAPTER_FIXED_CONTEXT_GATE:-dynamic}_conv${ADAPTER_CONV_TAG}"
else
  E2E_DEFAULT_TAG="${ADAPTER_TYPE}_lora_${LORA_TARGET_MODULES//,/-}_r${LORA_RANK}_a${LORA_ALPHA}_heads${ADAPTER_TOPK}_mem${ADAPTER_MEMORY_SIZE}_d${ADAPTER_HIDDEN_SIZE}_alpha${ADAPTER_USE_ALPHA_LAYER}-${ADAPTER_ALPHA_INIT}_gate${ADAPTER_FIXED_CONTEXT_GATE:-dynamic}_conv${ADAPTER_CONV_TAG}_sid${ADAPTER_USE_SID_SPAN}"
fi
export E2E_RUN_TAG="${E2E_RUN_TAG:-${ADAPTER_LORA_RUN_TAG:-$E2E_DEFAULT_TAG}}"
export E2E_MERGE_LORA=true
export E2E_STAGE2_BUNDLE_REMOTE_CODE=0
export E2E_SFT_BUNDLE_REMOTE_CODE=1
run_e2e_pipeline
